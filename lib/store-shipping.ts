export function calculateStoreDeliveryFee(subtotalKes: number, county: string, city: string) {
  const location = `${county} ${city}`.trim().toLowerCase();
  const isNairobi = location.includes("nairobi");
  if (isNairobi && subtotalKes >= FREE_NAIROBI_DELIVERY_THRESHOLD_KES) return 0;
  return isNairobi ? 300 : 500;
}
